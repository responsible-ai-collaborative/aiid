import { Collection, Document, MongoClient, ObjectId } from 'mongodb';

/**
 * Removes duplicate translation documents and adds a unique index on
 * (report_number, language) in `translations.reports` and on (incident_id, language) in
 * `translations.incidents`.
 *
 * Until October 2026 the report translation script cleared a `dirty` translation with an
 * update filtered on `report_number` alone, which rewrote the first document of any language
 * as the language being re-translated. The displaced language was then re-translated and
 * re-inserted on every daily run, so a handful of reports accumulated dozens of Japanese
 * documents, lost their Spanish ones, and were paid for again every day. The script now
 * upserts on (report_number, language); this migration cleans up what the old behaviour left
 * behind and makes the collection refuse duplicates from now on.
 */

interface Candidate {
  _id: ObjectId;
  dirty?: boolean;
  created_at?: Date;
}

/**
 * The document to keep out of a duplicate group: a clean (not dirty) one over a dirty one,
 * then the most recently created, then the most recently inserted, so the translation of the
 * current source text survives.
 */
export const pickKeeper = (docs: Candidate[]): Candidate => {
  const compare = (a: Candidate, b: Candidate): number => {
    const clean = (doc: Candidate) => (doc.dirty ? 0 : 1);

    if (clean(a) !== clean(b)) {
      return clean(a) - clean(b);
    }

    const created = (doc: Candidate) =>
      doc.created_at instanceof Date ? doc.created_at.getTime() : 0;

    if (created(a) !== created(b)) {
      return created(a) - created(b);
    }

    // ObjectIds generated by one process increase with insertion order
    return String(a._id) < String(b._id) ? -1 : String(a._id) > String(b._id) ? 1 : 0;
  };

  return docs.reduce((best, doc) => (compare(doc, best) > 0 ? doc : best));
};

/**
 * Deletes every document that shares `keyFields` with another, keeping the one `pickKeeper`
 * chooses from each group.
 */
export const dedupeTranslations = async (
  collection: Collection<Document>,
  keyFields: string[]
): Promise<{ groups: number; deleted: number }> => {
  const groups = await collection
    .aggregate([
      {
        $group: {
          _id: Object.fromEntries(keyFields.map((field) => [field, `$${field}`])),
          docs: { $push: { _id: '$_id', dirty: '$dirty', created_at: '$created_at' } },
          count: { $sum: 1 },
        },
      },
      { $match: { count: { $gt: 1 } } },
    ])
    .toArray();

  let deleted = 0;

  for (const group of groups) {
    const keeper = pickKeeper(group.docs);

    const idsToDelete = group.docs
      .filter((doc: Candidate) => !doc._id.equals(keeper._id))
      .map((doc: Candidate) => doc._id);

    const result = await collection.deleteMany({ _id: { $in: idsToDelete } });

    deleted += result.deletedCount ?? 0;
  }

  return { groups: groups.length, deleted };
};

/**
 * Creates a unique index on `key`, first dropping any index on the same keys that is not
 * unique (MongoDB refuses a second index on the same keys with different options).
 */
export const ensureUniqueIndex = async (
  collection: Collection<Document>,
  key: Record<string, 1 | -1>,
  name: string
): Promise<void> => {
  const indexes = await collection.indexes();

  for (const index of indexes) {
    if (index.name !== name && JSON.stringify(index.key) === JSON.stringify(key) && !index.unique) {
      await collection.dropIndex(index.name!);

      console.log(`Dropped non-unique index ${index.name} on ${collection.collectionName}`);
    }
  }

  await collection.createIndex(key, { unique: true, name });
};

const targets = [
  {
    collection: 'reports',
    keyFields: ['report_number', 'language'],
    indexName: 'report_number_language_unique',
  },
  {
    collection: 'incidents',
    keyFields: ['incident_id', 'language'],
    indexName: 'incident_id_language_unique',
  },
];

export const up = async ({ context: { client } }: { context: { client: MongoClient } }) => {
  const db = client.db('translations');

  for (const { collection: name, keyFields, indexName } of targets) {
    const collection = db.collection(name);

    const { groups, deleted } = await dedupeTranslations(collection, keyFields);

    console.log(
      `translations.${name}: deleted ${deleted} duplicate documents across ${groups} (${keyFields.join(
        ', '
      )}) groups`
    );

    await ensureUniqueIndex(
      collection,
      Object.fromEntries(keyFields.map((field) => [field, 1])) as Record<string, 1>,
      indexName
    );

    console.log(`translations.${name}: unique index ${indexName} in place`);
  }
};
